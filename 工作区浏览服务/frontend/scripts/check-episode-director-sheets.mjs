import assert from 'node:assert/strict';

export async function checkEpisodeDirectorSheets(page, fixture, width) {
  await fixture.getByRole('button', { name: '模拟整集六页', exact: true }).click();
  const materials = fixture.locator('.production-materials');
  await materials.locator(':scope > summary').click();
  assert.deepEqual(await materials.locator('[data-material-group="pending"] h3').allTextContents(), ['P010-参考图-001-候选-v10.png', 'P010-参考图-001-候选-v02.png', 'P002-参考图-001-候选-v01.png', 'P002-参考图-001.png'], '素材编号及候选版本按数值倒序');
  const history = materials.locator('[data-material-group="history"]');
  assert.equal(await history.getAttribute('open'), null, '旧版留档默认收起');
  assert.equal(await materials.locator('[data-material-group="adopted"] h3').innerText(), 'adopted.png', '当前采用不混入曾获批准旧版');
  assert.equal(await materials.locator('[data-material-group="revision"] .status-badge').innerText(), '待修改');
  assert.equal(await materials.locator('[data-material-group="unknown"] .status-badge').innerText(), '状态待核对');
  await history.locator('summary').click();
  assert.equal(await history.getByText('旧版留档（曾获批准）', { exact: true }).isVisible(), true);
  await history.locator('summary').click();
  await materials.getByRole('button', { name: '查看审阅记录', exact: true }).first().click();
  assert.equal(await page.getByRole('dialog').getByText('候选的具体审阅依据', { exact: true }).count(), 1);
  await page.keyboard.press('Escape');
  await materials.getByRole('button', { name: '查看P010-参考图-001-候选-v10.png', exact: true }).click();
  assert.equal(await page.getByRole('dialog').locator('img').getAttribute('alt'), 'P010-参考图-001-候选-v10.png');
  await page.keyboard.press('Escape');
  await materials.locator(':scope > summary').click();
  const scenes = fixture.getByRole('navigation', { name: '本集场次' });
  assert.deepEqual(await scenes.getByRole('button').allTextContents(), ['场次 C001', '场次 C002', '场次 C003', '场次 C004'], '没有独立整集入口');
  await scenes.getByRole('button', { name: '场次 C002', exact: true }).click();
  await fixture.getByRole('button', { name: '导演分镜表', exact: true }).click();
  const toggle = fixture.getByRole('checkbox', { name: '整合本集', exact: true });
  assert.equal(await toggle.isChecked(), false);
  await fixture.getByRole('navigation', { name: '导演分镜表页码' }).getByRole('button', { name: '2', exact: true }).click();
  const before = await fixture.locator('.director-sheet-image img').getAttribute('alt');
  await toggle.check();
  assert.equal(await fixture.locator('.director-sheet-image img').getAttribute('alt'), before, '整合保留当前场次图片位置');
  const viewer = fixture.getByRole('region', { name: '整集导演分镜表', exact: true });
  const image = viewer.locator('.director-sheet-image img');
  assert.equal(await viewer.locator('.director-sheet-record').getByRole('link', { name: '下载原图', exact: true }).count(), 1);
  assert.equal(await viewer.locator('.director-sheet-footer').count(), 0);
  const pages = viewer.getByRole('navigation', { name: '导演分镜表页码' });
  assert.deepEqual(await pages.getByRole('button').allTextContents(), ['1', '2', '3', '4', '5', '6']);
  assert.equal(await pages.getByRole('button', { name: '3', exact: true }).getAttribute('aria-current'), 'page');
  await pages.getByRole('button', { name: '1', exact: true }).click();
  assert.match(await image.getAttribute('alt'), /C001.*第01页/);
  assert.equal(await viewer.locator('.director-sheet-source').innerText(), '场次 C001', '整集仅显示所属场次');
  await viewer.getByRole('button', { name: '下一张图', exact: true }).click();
  assert.equal(await pages.getByRole('button', { name: '2', exact: true }).getAttribute('aria-current'), 'page');
  assert.equal(await viewer.locator('.director-sheet-source').innerText(), '场次 C002');
  assert.match(await image.getAttribute('alt'), /C002.*v01.*第01页/, '采用候选优先，页码按数值排序');
  await viewer.getByRole('button', { name: '查看记录', exact: true }).click();
  assert.equal(await page.getByRole('dialog').getByText('C002记录正文', { exact: true }).count(), 1, '记录跟随当前图片场次');
  await page.getByRole('dialog').getByRole('button', { name: '关闭', exact: true }).click();
  await pages.getByRole('button', { name: '4', exact: true }).click();
  await viewer.getByRole('button', { name: '全屏查看第04页导演分镜表', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByRole('button', { name: '下一张图', exact: true }).click();
  assert.match(await dialog.locator('img').getAttribute('alt'), /C003/);
  await dialog.getByRole('button', { name: '下一张图', exact: true }).click();
  assert.match(await dialog.locator('img').getAttribute('alt'), /C004/);
  assert.equal(await dialog.getByRole('button', { name: '下一张图', exact: true }).count(), 0);
  await page.keyboard.press('Escape');
  assert.equal(await pages.getByRole('button', { name: '6', exact: true }).getAttribute('aria-current'), 'page');
  await pages.getByRole('button', { name: '2', exact: true }).click();
  await viewer.getByRole('combobox', { name: '导演分镜表候选', exact: true }).click();
  await page.getByRole('option', { name: '候选2（1张）', exact: true }).click();
  assert.equal(await pages.getByRole('button').count(), 4);
  assert.equal(await pages.getByRole('button', { name: '2', exact: true }).getAttribute('aria-current'), 'page');
  assert.match(await image.getAttribute('alt'), /C002.*v02/);
  await viewer.getByRole('button', { name: '上一张图', exact: true }).click();
  assert.match(await image.getAttribute('alt'), /C001.*v01/, '不同场次候选选择相互独立');
  await viewer.getByRole('button', { name: '下一张图', exact: true }).click();
  await toggle.uncheck();
  assert.match(await fixture.locator('.director-sheet-image img').getAttribute('alt'), /C002/, '取消整合回到上方当前场次');
  const round = fixture.getByRole('combobox', { name: '场次修改轮次', exact: true });
  await round.click();
  await page.getByRole('option', { name: '第1轮：剧本缺失 · 分镜v01', exact: true }).click();
  await toggle.check();
  assert.equal(await viewer.getByText('场次 C002：分镜 v01 尚未制作导演分镜表。', { exact: true }).count(), 1, '当前场次保留所选旧轮次，不借用新轮次图片');
  assert.equal(await pages.getByRole('button').count(), 3);
  await scenes.getByRole('button', { name: '场次 C001', exact: true }).click();
  assert.equal(await toggle.isChecked(), true, '切场保留整合勾选及导演表标签');
  assert.equal(await pages.getByRole('button').count(), 6, '其他场次取最新轮次，忽略之前选过的旧轮次');
  await pages.getByRole('button', { name: '2', exact: true }).click();
  assert.match(await image.getAttribute('alt'), /C002.*v01/);
  await fixture.getByRole('button', { name: '模拟其他场次最新轮次无图', exact: true }).click();
  await viewer.getByText('场次 C003：分镜 v08 尚未制作导演分镜表。', { exact: true }).waitFor({ state: 'visible' });
  assert.equal(await pages.getByRole('button').count(), 5, '最新轮次缺图时不回退到旧图');
  await toggle.uncheck();
  assert.match(await fixture.locator('.director-sheet-image img').getAttribute('alt'), /C001/);
  await toggle.check();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await viewer.screenshot({ path: `/tmp/nora-w385-viewer-${width}.png` });
  console.log(`整集导演表：${width}px整合开关、定位保留、场次边界、全屏、候选及记录跟随、最新轮次与缺图提示通过。`);
}
